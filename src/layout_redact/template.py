"""Template format: the reference layout of one form and where to redact it.

A template is a small YAML (or JSON) file:

.. code-block:: yaml

    format: layout-redact/template@1
    name: sample-order-form
    page_size: [1240, 1754]          # reference raster size in px (width, height)
    frame: [[80, 80], [1160, 80], [1160, 1674], [80, 1674]]   # auto: outer quad
    keypoints:                        # auto: line junctions [x, y, arms]
      - [80.0, 80.0, RD]
      - ...
    regions:                          # what to redact, in reference px
      - name: customer_name
        box: [300, 210, 610, 265]     # x0, y0, x1, y1
      - name: signature
        polygon: [[760, 1460], [1160, 1460], [1160, 1620], [760, 1620]]
        pad: 4                        # optional, grows the region (px)
        fill: [0, 0, 0]               # optional, RGB

``frame`` and ``keypoints`` are generated by :func:`build_template` from a
clean reference image; you only write ``regions`` (by hand, from a script, or
with ``layout-redact annotate``).
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Union

import numpy as np
import yaml

from .skeleton import SkeletonParams, arms_from_str, arms_to_str, extract_skeleton, frame_candidates

FORMAT_ID = "layout-redact/template@1"
PathLike = Union[str, Path]


@dataclass
class Region:
    name: str
    polygon: np.ndarray            # (N, 2) float, reference px
    pad: float = 0.0
    fill: tuple = (0, 0, 0)        # RGB

    @classmethod
    def from_box(cls, name: str, box: Sequence[float], **kw) -> "Region":
        x0, y0, x1, y1 = [float(v) for v in box]
        x0, x1 = min(x0, x1), max(x0, x1)
        y0, y1 = min(y0, y1), max(y0, y1)
        return cls(name, np.array([[x0, y0], [x1, y0], [x1, y1], [x0, y1]], np.float64), **kw)

    def padded(self) -> np.ndarray:
        """Polygon grown by ``pad`` px away from its centroid (exact for boxes)."""
        if not self.pad:
            return self.polygon.copy()
        poly = self.polygon
        if len(poly) == 4 and _is_axis_box(poly):
            x0, y0 = poly.min(axis=0) - self.pad
            x1, y1 = poly.max(axis=0) + self.pad
            return np.array([[x0, y0], [x1, y0], [x1, y1], [x0, y1]], np.float64)
        c = poly.mean(axis=0)
        d = poly - c
        n = np.linalg.norm(d, axis=1, keepdims=True)
        n[n == 0] = 1.0
        return poly + d / n * self.pad

    def to_dict(self) -> Dict[str, Any]:
        d: Dict[str, Any] = {"name": self.name}
        if len(self.polygon) == 4 and _is_axis_box(self.polygon):
            x0, y0 = self.polygon.min(axis=0)
            x1, y1 = self.polygon.max(axis=0)
            d["box"] = [_r(x0), _r(y0), _r(x1), _r(y1)]
        else:
            d["polygon"] = [[_r(x), _r(y)] for x, y in self.polygon]
        if self.pad:
            d["pad"] = _r(self.pad)
        if tuple(self.fill) != (0, 0, 0):
            d["fill"] = list(self.fill)
        return d


@dataclass
class Template:
    name: str
    page_size: tuple                         # (width, height)
    frame: np.ndarray                        # (4, 2) clockwise from top-left
    keypoints: np.ndarray                    # (N, 2)
    keypoint_arms: np.ndarray                # (N,) int bitmasks
    regions: List[Region] = field(default_factory=list)
    description: str = ""
    params: Dict[str, Any] = field(default_factory=dict)  # optional overrides

    @property
    def width(self) -> int:
        return int(self.page_size[0])

    @property
    def height(self) -> int:
        return int(self.page_size[1])

    # -- serialisation -----------------------------------------------------
    def to_dict(self) -> Dict[str, Any]:
        d: Dict[str, Any] = {
            "format": FORMAT_ID,
            "name": self.name,
        }
        if self.description:
            d["description"] = self.description
        d["page_size"] = [int(self.page_size[0]), int(self.page_size[1])]
        d["frame"] = [[_r(x), _r(y)] for x, y in self.frame]
        d["regions"] = [r.to_dict() for r in self.regions]
        if self.params:
            d["params"] = dict(self.params)
        d["keypoints"] = [
            [_r(x), _r(y), arms_to_str(int(a))] for (x, y), a in zip(self.keypoints, self.keypoint_arms)
        ]
        return d

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> "Template":
        fmt = d.get("format", FORMAT_ID)
        if fmt != FORMAT_ID:
            raise ValueError(f"Unsupported template format: {fmt!r}")
        for key in ("name", "page_size", "frame", "keypoints"):
            if key not in d:
                raise ValueError(f"Template is missing required key {key!r}")
        kps = d["keypoints"] or []
        pts = np.array([[float(k[0]), float(k[1])] for k in kps], np.float64).reshape(-1, 2)
        arms = np.array([arms_from_str(str(k[2])) if len(k) > 2 else 15 for k in kps], np.int32)
        regions = []
        for r in d.get("regions", []) or []:
            kw = {"pad": float(r.get("pad", 0.0)), "fill": tuple(r.get("fill", (0, 0, 0)))}
            if "box" in r:
                regions.append(Region.from_box(r["name"], r["box"], **kw))
            elif "polygon" in r:
                poly = np.array(r["polygon"], np.float64).reshape(-1, 2)
                if len(poly) < 3:
                    raise ValueError(f"Region {r['name']!r}: polygon needs >= 3 points")
                regions.append(Region(r["name"], poly, **kw))
            else:
                raise ValueError(f"Region {r.get('name')!r} needs 'box' or 'polygon'")
        frame = np.array(d["frame"], np.float64).reshape(4, 2)
        return cls(
            name=str(d["name"]),
            page_size=(int(d["page_size"][0]), int(d["page_size"][1])),
            frame=frame,
            keypoints=pts,
            keypoint_arms=arms,
            regions=regions,
            description=str(d.get("description", "")),
            params=dict(d.get("params", {}) or {}),
        )

    def save(self, path: PathLike) -> None:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        d = self.to_dict()
        if path.suffix.lower() == ".json":
            path.write_text(json.dumps(d, indent=1), encoding="utf-8")
        else:
            path.write_text(_dump_yaml(d), encoding="utf-8")

    @classmethod
    def load(cls, path: PathLike) -> "Template":
        path = Path(path)
        text = path.read_text(encoding="utf-8")
        data = json.loads(text) if path.suffix.lower() == ".json" else yaml.safe_load(text)
        return cls.from_dict(data)


def build_template(reference: np.ndarray, regions: Sequence[Union[Region, Dict[str, Any]]],
                   name: str, description: str = "",
                   params: Optional[SkeletonParams] = None) -> Template:
    """Create a template from a clean, upright reference image.

    The reference should be the form at the resolution you will define the
    regions in (150 dpi is a good default), ideally a blank or digitally
    generated page rather than a phone photo.
    """
    h, w = reference.shape[:2]
    sk = extract_skeleton(reference, params)
    frame = frame_candidates(reference, max_candidates=1, params=params)[0]
    regs: List[Region] = []
    for r in regions:
        if isinstance(r, Region):
            regs.append(r)
        else:
            regs.extend(Template.from_dict({
                "name": "_", "page_size": [w, h], "frame": frame.tolist(),
                "keypoints": [], "regions": [r],
            }).regions)
    if len(sk.junctions) < 8:
        raise ValueError(
            f"Only {len(sk.junctions)} line junctions found in the reference; "
            "layout-redact needs a form with ruled lines/boxes (>= 8 junctions)."
        )
    return Template(
        name=name,
        page_size=(w, h),
        frame=frame,
        keypoints=sk.points(),
        keypoint_arms=sk.arms(),
        regions=regs,
        description=description,
    )


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def _r(v: float) -> float:
    v = round(float(v), 1)
    return int(v) if v.is_integer() else v


def _is_axis_box(poly: np.ndarray) -> bool:
    xs = sorted(set(np.round(poly[:, 0], 3)))
    ys = sorted(set(np.round(poly[:, 1], 3)))
    return len(xs) == 2 and len(ys) == 2


class _FlowList(list):
    pass


def _flow_list_representer(dumper, data):
    return dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=True)


class _Dumper(yaml.SafeDumper):
    pass


_Dumper.add_representer(_FlowList, _flow_list_representer)


def _dump_yaml(d: Dict[str, Any]) -> str:
    """YAML with short lists (points, boxes, keypoints) written inline."""

    def conv(o):
        if isinstance(o, dict):
            return {k: conv(v) for k, v in o.items()}
        if isinstance(o, list):
            items = [conv(v) for v in o]
            if all(not isinstance(v, (dict, list)) for v in items) or \
                    all(isinstance(v, _FlowList) and len(v) <= 3 for v in items) and len(items) <= 8:
                return _FlowList(items)
            return items
        return o

    return yaml.dump(conv(d), Dumper=_Dumper, sort_keys=False, width=100)
